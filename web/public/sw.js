// Минимальный сервис-воркер: нужен браузеру, чтобы предложить «Установить приложение» / «На экран Домой».
// Ничего не кэширует и запросы не перехватывает: данные клуба и новые версии сайта всегда берутся из сети,
// поэтому устаревшей копии приложения (и устаревших данных детей) не бывает.
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', e => e.waitUntil(self.clients.claim()));
self.addEventListener('fetch', () => {});
